const fs = require("node:fs");
const path = require("node:path");
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

/**
 * Permit cleartext HTTP to the configured bench host, and to nothing else.
 *
 * Android has blocked cleartext by default since API 28. Expo Go's own manifest
 * allows it, which is why the dev-server build works and a standalone APK
 * silently fails every API call instead.
 *
 * The obvious fix — `usesCleartextTraffic: true` — opens the whole app to
 * plaintext on any host. On a BYOD handset carrying operational data over resort
 * and staff-home Wi-Fi (AD-016-007) that is a poor trade for a dev convenience,
 * so this scopes the exception to one hostname taken from `extra.apiBaseUrl`.
 *
 * Written as a plugin rather than an edit under `android/` because prebuild
 * regenerates that directory, and a fix that disappears on the next build is not
 * a fix.
 *
 * Does nothing when the API base is https — production needs no exception, and
 * this must not quietly weaken a real build.
 */
function benchHost(config) {
	const apiBaseUrl = config.extra?.apiBaseUrl;
	if (!apiBaseUrl) return null;
	try {
		const url = new URL(apiBaseUrl);
		return url.protocol === "http:" ? url.hostname : null;
	} catch {
		return null;
	}
}

const networkSecurityConfig = (host) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBenchCleartext.js. Do not edit; prebuild overwrites it. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">${host}</domain>
    </domain-config>
</network-security-config>
`;

module.exports = function withBenchCleartext(config) {
	const host = benchHost(config);
	if (!host) return config;

	config = withDangerousMod(config, [
		"android",
		async (inner) => {
			const dir = path.join(
				inner.modRequest.platformProjectRoot,
				"app/src/main/res/xml",
			);
			fs.mkdirSync(dir, { recursive: true });
			fs.writeFileSync(
				path.join(dir, "network_security_config.xml"),
				networkSecurityConfig(host),
			);
			return inner;
		},
	]);

	return withAndroidManifest(config, (inner) => {
		const application = AndroidConfig.Manifest.getMainApplicationOrThrow(inner.modResults);
		application.$["android:networkSecurityConfig"] = "@xml/network_security_config";
		// Explicit default-deny. The config above is what grants the one exception.
		application.$["android:usesCleartextTraffic"] = "false";
		return inner;
	});
};
